"""
Driver analysis ("what moved the number").

Pick a measure, a month and a comparison. For every dimension the measure can
be split by, the engine computes each segment's exact share of the change (see
measures.py for the arithmetic), ranks them, checks that everything adds up,
and says whether the move is unusual compared with the measure's own history.

Nothing here is estimated, trained or generated by a model, and nothing is
typed in: every figure comes from the data frames the dashboards already use.
The text is assembled from those figures by fixed templates.

What it does NOT do: say WHY. A segment that carries 90% of a change is where
to look, not proof of the cause; the response says so.
"""

from __future__ import annotations

import math

import pandas as pd

from app.config import (RCA_CONCENTRATED_PCT, RCA_MIN_RELATIVE_CHANGE_PCT, RCA_MODERATE_PCT,
                        RCA_NEGLIGIBLE_DELTA, RCA_TOP_N)
from app.filters import Filters
from app.formatting import inr_compact
from app.rca import evidence as ev
from app.rca.dims import DIMS
from app.rca.measures import (COMPARE_LABELS, MEASURES, Base, Contribs, Measure,
                              RcaError, Scope)


# --------------------------------------------------------------------------
# Inputs
# --------------------------------------------------------------------------
def months_available(store) -> pd.DatetimeIndex:
    ms = pd.concat([pd.to_datetime(store.consumption["Month_Start"]),
                    pd.to_datetime(store.inventory["Month_Start"])])
    return pd.DatetimeIndex(sorted(ms.unique()))


def parse_month(s: str, months: pd.DatetimeIndex) -> pd.Timestamp:
    try:
        m = pd.Timestamp(f"{s}-01")
    except Exception:
        raise RcaError("Month must look like 2026-05.")
    if m not in months:
        raise RcaError(f"There is no data for {s}.")
    return m


def get_measure(key: str) -> Measure:
    if key not in MEASURES:
        raise RcaError(f"Unknown metric '{key}'.")
    return MEASURES[key]


def make_base(measure: Measure, compare_key: str, m: pd.Timestamp, months: pd.DatetimeIndex) -> Base:
    if compare_key not in measure.compares:
        raise RcaError(f"{measure.label} cannot be compared with "
                       f"{COMPARE_LABELS.get(compare_key, compare_key).lower()}.")
    if compare_key == "prior_month":
        bm = m - pd.DateOffset(months=1)
        label = bm.strftime("%b %Y")
    elif compare_key == "same_month_last_year":
        bm = m - pd.DateOffset(months=12)
        label = bm.strftime("%b %Y")
    elif compare_key == "budget":
        return Base("budget", "budget", "Budget")
    else:
        return Base("target", "target", f"Target ({measure.target:.0f}%)")
    if bm not in months:
        raise RcaError(f"There is no data for {label}, so {m.strftime('%b %Y')} cannot be compared with "
                       f"{COMPARE_LABELS[compare_key].lower()}.")
    return Base("month", compare_key, label, bm)


def parse_path(parts: list[str], measure: Measure, compare_key: str) -> list[tuple[str, str]]:
    conds: list[tuple[str, str]] = []
    allowed = measure.dims_for(compare_key)
    for p in parts or []:
        dim, sep, val = p.partition(":")
        if not sep or dim not in DIMS:
            raise RcaError(f"Bad drill step '{p}'.")
        if dim not in allowed:
            raise RcaError(f"{measure.label} cannot be split by {DIMS[dim].label.lower()}"
                           f"{' when compared with budget' if compare_key == 'budget' else ''}.")
        if any(d == dim for d, _ in conds):
            raise RcaError(f"{DIMS[dim].label} is already part of the drill path.")
        conds.append((dim, val))
    return conds


# --------------------------------------------------------------------------
# Small helpers
# --------------------------------------------------------------------------
def num(x) -> float | None:
    try:
        x = float(x)
    except (TypeError, ValueError):
        return None
    return x if math.isfinite(x) else None


def fmt_value(measure: Measure, v: float | None) -> str:
    if v is None:
        return "n/a"
    if measure.fmt == "currency":
        return inr_compact(v)
    if measure.fmt == "percent":
        return f"{v:.1f}%"
    return f"{v:.1f} days"


def fmt_delta(measure: Measure, v: float) -> str:
    a = abs(v)
    if measure.fmt == "currency":
        return inr_compact(a)
    if measure.fmt == "percent":
        return f"{a:.2f} pp"
    return f"{a:.2f} days" if a < 1 else f"{a:.1f} days"


def is_flat(delta: float, base_val: float) -> bool:
    """A net change too small to attribute: shares of it would be dominated by offsetting moves."""
    return abs(delta) < max(RCA_NEGLIGIBLE_DELTA, RCA_MIN_RELATIVE_CHANGE_PCT / 100.0 * abs(base_val or 0.0))


def pattern_of(share: float | None) -> str | None:
    if share is None:
        return None
    return ("Concentrated" if share >= RCA_CONCENTRATED_PCT
            else "Moderate" if share >= RCA_MODERATE_PCT else "Spread out")


def _tone(measure: Measure, delta: float, flat: bool) -> str:
    if flat or measure.higher_is == "neutral":
        return "neutral"
    good = (delta > 0) == (measure.higher_is == "better")
    return "good" if good else "bad"


# --------------------------------------------------------------------------
# Evidence for a headline or a segment
# --------------------------------------------------------------------------
def headline_evidence(measure: Measure, sc: Scope, m: pd.Timestamp, base: Base) -> dict:
    bser = measure.root_budget_series(sc) if base.kind == "budget" else None
    q, basis = ev.quantity(measure.kind, measure.root_series(sc), base.key, bser)
    out = ev.verdict(q, m, basis)
    # Seasonality check for additive measures: did the same calendar month move the same way last year?
    if out.get("available") and measure.kind != "ratio" and q is not None:
        ly = m - pd.DateOffset(months=12)
        if ly in q.index and pd.notna(q.loc[ly]):
            out["same_month_last_year"] = {"month": ly.strftime("%b %Y"), "value": num(q.loc[ly])}
    return out


def _segment_evidence(measure: Measure, base: Base, wide: pd.DataFrame | None,
                      bwide: pd.DataFrame | None, seg: str, m: pd.Timestamp) -> dict:
    if wide is None or seg not in wide.columns:
        return {"available": False, "reason": "No history for this segment."}
    bser = None
    if base.kind == "budget":
        if bwide is None or seg not in bwide.columns:
            return {"available": False, "reason": "No budget history for this segment."}
        bser = bwide[seg]
    q, basis = ev.quantity(measure.kind, wide[seg], base.key, bser)
    return ev.verdict(q, m, basis, with_history=True)


# --------------------------------------------------------------------------
# One dimension -> ranked rows
# --------------------------------------------------------------------------
def dimension_block(measure: Measure, sc: Scope, dim: str, m: pd.Timestamp, base: Base,
                    delta: float, negligible: bool) -> tuple[dict | None, Contribs]:
    cb = measure.contributions(sc, dim, m, base)
    fr = cb.frame
    fr = fr[(fr["contribution"].abs() > 0) | (fr["own_current"].fillna(0).abs() > 0)]
    if len(fr) < 2:
        return None, cb
    sgn = 1.0 if delta >= 0 else -1.0

    def share(c: float) -> float | None:
        return None if negligible else c / delta * 100

    aligned = (fr["contribution"] * sgn)
    top1 = float(aligned.max())
    top1_share = None if negligible else top1 / abs(delta) * 100
    top3_share = None if negligible else float(aligned.sort_values(ascending=False).head(3).clip(lower=0).sum()) / abs(delta) * 100

    order = fr["contribution"].abs().sort_values(ascending=False).index[:RCA_TOP_N]
    shown = fr.loc[order].assign(_k=lambda d: d["contribution"] * sgn).sort_values("_k", ascending=False)

    wide = measure.seg_series(sc, dim)
    bwide = measure.seg_budget_series(sc, dim) if base.kind == "budget" else None

    rows = []
    for seg, r in shown.iterrows():
        row = {
            "segment": seg,
            "contribution": num(r["contribution"]),
            "share_pct": num(share(r["contribution"])),
            "own_current": num(r["own_current"]),
            "own_base": num(r["own_base"]),
            "weight_pct": num(r["weight"]),
            "evidence": _segment_evidence(measure, base, wide, bwide, seg, m),
        }
        parts = {}
        if "stock_effect" in fr.columns:
            parts["Stock"] = num(r["stock_effect"])
        if "consumption_effect" in fr.columns:
            parts["Consumption"] = num(r["consumption_effect"])
        if parts and base.kind == "month":
            row["parts"] = parts
        rows.append(row)

    rest = fr.drop(index=order)
    other = None
    if len(rest):
        other = {"label": f"All other ({len(rest)})", "count": int(len(rest)),
                 "contribution": num(rest["contribution"].sum()),
                 "share_pct": num(share(rest["contribution"].sum()))}

    top_seg = aligned.idxmax()
    block = {
        "key": dim, "label": DIMS[dim].label,
        "segments": int(len(fr)),
        "rows": rows, "other": other,
        "top_segment": top_seg if top1 > 0 else None,
        "top1_share_pct": num(top1_share), "top3_share_pct": num(top3_share),
        "pattern": pattern_of(top1_share),
        # One segment moved MORE than the whole net change because others moved the other way.
        "offsets": bool(top1_share is not None and top1_share > 100.0),
        "total": num(fr["contribution"].sum()),
        # Gross movement: how much the segments moved in total, ignoring direction.
        "gross": num(fr["contribution"].abs().sum()),
        "biggest_up": ({"segment": fr["contribution"].idxmax(), "contribution": num(fr["contribution"].max())}
                       if fr["contribution"].max() > 0 else None),
        "biggest_down": ({"segment": fr["contribution"].idxmin(), "contribution": num(fr["contribution"].min())}
                         if fr["contribution"].min() < 0 else None),
    }
    return block, cb


# --------------------------------------------------------------------------
# The analysis
# --------------------------------------------------------------------------
def analyze(store, f: Filters, metric_key: str, month: str, compare_key: str,
            path: list[str] | None = None) -> dict:
    measure = get_measure(metric_key)
    months = months_available(store)
    m = parse_month(month, months)
    base = make_base(measure, compare_key, m, months)
    conds = parse_path(path or [], measure, compare_key)

    root = Scope(store, f, [])
    if base.kind == "budget" and root.bud_reason:
        raise RcaError(root.bud_reason)
    cur = measure.root_value(root, m)
    if cur is None:
        raise RcaError(f"No {measure.label.lower()} data for {m.strftime('%b %Y')} in this scope.")
    base_val = measure.base_value(root, m, base)
    if base_val is None:
        raise RcaError(f"No data for {base.label} in this scope.")
    delta = cur - base_val
    negligible = is_flat(delta, base_val)

    sc = root.with_conds(conds) if conds else root
    used = {d for d, _ in conds}
    blocks, gaps, slice_totals, effects = [], [], [], []
    for dim in measure.dims_for(compare_key):
        if dim in used:
            continue
        block, cb = dimension_block(measure, sc, dim, m, base, delta, negligible)
        slice_totals.append(cb.slice_total)
        if not conds and not effects:
            effects = cb.effects
        if block:
            blocks.append(block)
    # --- truthfulness check: every dimension must add up to the same total
    ref_total = (slice_totals[0] if slice_totals else 0.0)
    eff_total = sum(e["contribution"] for e in effects) if not conds else 0.0
    gaps = [abs(t - ref_total) for t in slice_totals]
    if not conds:
        gaps.append(abs(ref_total + eff_total - delta))
    max_gap = max(gaps) if gaps else 0.0
    tol = 1e-6 * max(1.0, abs(delta), abs(cur))
    reconciliation = {"ok": bool(max_gap <= tol), "max_gap": num(max_gap),
                      "checked": "Every split adds up to the change in the whole"
                                 if not conds else "Every split adds up to the same slice total"}

    # --- drill chain
    chain = [{"label": "All (selected scope)", "dim": None, "segment": None,
              "contribution": num(delta), "share_pct": None if negligible else 100.0}]
    for i, (dim, val) in enumerate(conds):
        c_i = measure.contributions(root.with_conds(conds[: i + 1]), None, m, base)
        chain.append({"label": f"{DIMS[dim].label}: {val}", "dim": dim, "segment": val,
                      "contribution": num(c_i.slice_total),
                      "share_pct": None if negligible else num(c_i.slice_total / delta * 100)})

    # --- suggestion for the next drill step: the most concentrated dimension
    suggestion = None
    cands = [b for b in blocks if b["top_segment"] and b["top1_share_pct"] is not None]
    if cands:
        best = max(cands, key=lambda b: b["top1_share_pct"])
        suggestion = {"dim": best["key"], "dim_label": best["label"], "segment": best["top_segment"],
                      "share_pct": best["top1_share_pct"], "pattern": best["pattern"]}

    headline = {
        "current": num(cur), "base": num(base_val), "delta": num(delta),
        "delta_pct": None if (measure.kind == "ratio" or not base_val) else num(delta / base_val * 100),
        "tone": _tone(measure, delta, negligible), "flat": negligible,
    }
    evidence = headline_evidence(measure, root, m, base)

    out = {
        "metric": {"key": measure.key, "label": measure.label, "fmt": measure.fmt,
                   "unit_word": measure.unit_word, "higher_is": measure.higher_is,
                   "definition": measure.definition, "weight_label": measure.weight_label},
        "period": {"month": m.strftime("%Y-%m"), "label": m.strftime("%b %Y")},
        "compare": {"key": base.key, "label": base.label,
                    "base_month": base.month.strftime("%Y-%m") if base.month is not None else None},
        "scope": {"filters": f.as_dict(),
                  "path": [{"dim": d, "dim_label": DIMS[d].label, "value": v} for d, v in conds]},
        "headline": headline,
        "effects": [{"label": e["label"], "contribution": num(e["contribution"])} for e in effects],
        "dimensions": blocks,
        "unavailable_dimensions": [
            {"key": k, "label": d.label,
             "reason": ("budget is only set by unit and department" if compare_key == "budget"
                        and k in measure.dims else "not recorded in this measure's data")}
            for k, d in DIMS.items()
            if k not in measure.dims_for(compare_key) and k not in used
        ],
        "chain": chain,
        "suggestion": suggestion,
        "evidence": evidence,
        "reconciliation": reconciliation,
    }
    out["narrative"] = narrate(measure, out)
    return out


# --------------------------------------------------------------------------
# Plain-English summary, assembled from the numbers above by fixed templates
# --------------------------------------------------------------------------
def narrate(measure: Measure, a: dict) -> list[str]:
    h, p, c = a["headline"], a["period"]["label"], a["compare"]
    cur, base, delta = h["current"], h["base"], h["delta"]
    lines: list[str] = []
    scope_path = a["scope"]["path"]

    flat = h["flat"]
    if flat:
        lines.append(f"{measure.label} was {fmt_value(measure, cur)} in {p}, essentially flat versus {c['label']} "
                     f"({fmt_value(measure, base)}; net {fmt_delta(measure, delta)}).")
        movers = max((b for b in a["dimensions"] if b["biggest_up"] and b["biggest_down"]),
                     key=lambda b: b["gross"] or 0, default=None)
        if movers:
            up, dn = movers["biggest_up"], movers["biggest_down"]
            lines.append(f"The flat total hides movement in opposite directions: by {movers['label'].lower()}, "
                         f"{up['segment']} added {fmt_delta(measure, up['contribution'])} while {dn['segment']} "
                         f"took off {fmt_delta(measure, dn['contribution'])}. Shares of a near-zero change are not shown.")
    else:
        up = delta > 0
        if c["key"] == "target":
            lines.append(f"{measure.label} was {fmt_value(measure, cur)} in {p}, "
                         f"{fmt_delta(measure, delta)} {'above' if up else 'below'} the target of {fmt_value(measure, base)}.")
        elif c["key"] == "budget":
            lines.append(f"{measure.label} was {fmt_value(measure, cur)} in {p}, "
                         f"{fmt_delta(measure, delta)} {'above' if up else 'below'} budget ({fmt_value(measure, base)}).")
        else:
            pct = f" ({abs(h['delta_pct']):.1f}%)" if h.get("delta_pct") is not None else ""
            lines.append(f"{measure.label} was {fmt_value(measure, cur)} in {p}, "
                         f"{'up' if up else 'down'} {fmt_delta(measure, delta)}{pct} from "
                         f"{c['label']} ({fmt_value(measure, base)}).")
        for e in a["effects"]:
            if e["contribution"] is not None and abs(e["contribution"]) > RCA_NEGLIGIBLE_DELTA:
                lines.append(f"{e['label']} accounts for {fmt_delta(measure, e['contribution'])} of it "
                             f"(months have different lengths).")
        found = [b for b in a["dimensions"]
                 if b["top1_share_pct"] is not None and b["top1_share_pct"] >= RCA_MODERATE_PCT and b["top_segment"]]
        found.sort(key=lambda b: -b["top1_share_pct"])

        def phrase(b):
            seg = next(r for r in b["rows"] if r["segment"] == b["top_segment"])
            if b["offsets"]:
                return (f"{b['top_segment']} ({b['label'].lower()}) moved {fmt_delta(measure, seg['contribution'])}, "
                        f"more than the whole net change, because other segments moved the opposite way")
            return f"{b['top1_share_pct']:.0f}% of the change is {b['top_segment']} ({b['label'].lower()})"
        if found:
            lead = "Inside the drilled slice: " if scope_path else "Where it sits: "
            lines.append(lead + "; ".join(phrase(b) for b in found[:3]) + ".")
        else:
            spread = max((b for b in a["dimensions"] if b["top1_share_pct"] is not None),
                         key=lambda b: b["top1_share_pct"], default=None)
            tail = (f" The largest single share is {spread['top1_share_pct']:.0f}% "
                    f"({spread['top_segment']}, {spread['label'].lower()})." if spread and spread["top_segment"] else "")
            lines.append("The change is spread out: no single segment explains most of it." + tail)

    e = a["evidence"]
    if e.get("available"):
        z = e["z"]
        if e["basis"] == "level":
            where = f"{fmt_value(measure, e['value'])} versus a usual {fmt_value(measure, e['mean'])} (± {fmt_delta(measure, e['sd'])})"
        else:
            where = (f"{fmt_delta(measure, e['value'])} {'increase' if e['value'] >= 0 else 'decrease'} versus a typical "
                     f"{'+' if e['mean'] >= 0 else '-'}{fmt_delta(measure, e['mean'])} ± {fmt_delta(measure, e['sd'])}")
        verdict = {"unusual": "unusual", "watch": "somewhat out of the ordinary", "normal": "within its normal range"}[e["flag"]]
        lines.append(f"Compared with the other {e['n']} months, the {e['basis']} is {verdict} "
                     f"({abs(z):.1f} standard deviations {'above' if z > 0 else 'below'} normal; {where}).")
        ly = e.get("same_month_last_year")
        if ly and ly["value"] is not None and e["value"] and (ly["value"] * e["value"] > 0) \
                and abs(ly["value"]) >= 0.5 * abs(e["value"]):
            lines.append(f"{ly['month']} moved the same way ({'+' if ly['value'] >= 0 else '-'}{fmt_delta(measure, ly['value'])}), "
                         f"so part of this may be seasonal.")
    else:
        lines.append(f"Not enough history to judge whether this is unusual ({e.get('reason', '')}).")
    return lines
